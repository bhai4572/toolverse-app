export function getCvTemplateById(id: string): CvTemplateDefinition {
  return CV_TEMPLATES.find((t) => t.id === id) || CV_TEMPLATES[0];
}

export function applyTemplateDefaultsToDesign(
  current: CvDesignSettings,
  templateId: string,
  resetCustomizations = false
): CvDesignSettings {
  const tpl = getCvTemplateById(templateId);
  if (resetCustomizations) {
    return {
      ...current,
      templateId: tpl.id,
      accentColor: tpl.defaultAccent,
      fontFamily: tpl.defaultFont,
      fontSize: tpl.defaultFontSize,
      sectionSpacing: tpl.defaultSpacing,
      pageMargin: tpl.defaultMargin,
      photoVisibility: tpl.defaultPhoto,
      sidebarMode: tpl.defaultSidebar,
      headingStyle: tpl.defaultHeadingStyle,
    };
  }
  return {
    ...current,
    templateId: tpl.id,
    accentColor: tpl.defaultAccent,
    fontFamily: tpl.defaultFont,
    photoVisibility: tpl.defaultPhoto,
    sidebarMode: tpl.defaultSidebar,
    headingStyle: tpl.defaultHeadingStyle,
  };
}

