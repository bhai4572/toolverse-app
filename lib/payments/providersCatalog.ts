interface QuickProviderSpec {
  id: string;
  slug: string;
  officialName: string;
  brandName: string;
  color: string;
  cat: PaymentCategorySlug;
  secCats?: PaymentCategorySlug[];
  type: ProviderTypeClassification;
  shortDesc: string;
  intro: string;
  overview: string;
  website: string;
  docs: string;
  pricingUrl?: string;
  merchantCountries: string[];
  merchantNote: string;
  customerCountries?: string[];
  customerNote?: string;
  currencies: string[];
  settlementCurrencies: string[];
  fees: string;
  monthlyFees?: string;
  recurring: boolean;
  subscriptions: boolean;
  inPerson?: boolean;
  complexity?: 'Low' | 'Medium' | 'High';
  kyc: string;
  features: string[];
  pros: string[];
  cons: string[];
  alts: string[];
  methods: string[];
  crypto?: CryptoPaymentMetadata;
  rank: number;
}

function makeProvider(s: QuickProviderSpec): PaymentProvider {
  const seed: CompactEntrySeed = {
    id: s.id,
    slug: s.slug,
    entryKind: 'provider',
    officialName: s.officialName,
    brandName: s.brandName,
    brandColor: s.color,
    primaryCategorySlug: s.cat,
    secondaryCategorySlugs: s.secCats || [],
    providerType: s.type,
    shortDescription: s.shortDesc,
    uniqueIntroduction: s.intro,
    overview: s.overview,
    howItWorks: [
      `Merchant integrates ${s.brandName} via REST API, hosted checkout session, or e-commerce plugin.`,
      `Customer authorizes payment using supported cards, wallets, bank rails, or digital assets.`,
      `${s.brandName} verifies fraud/3DS2 signals and settles net proceeds in ${s.settlementCurrencies.slice(0, 4).join(', ')}.`,
    ],
    officialWebsite: s.website,
    documentationUrl: s.docs,
    pricingUrl: s.pricingUrl || s.website,
    apiAvailable: true,
    sdkAvailable: true,
    pluginAvailable: true,
    supportedPlatforms: ['Web', 'iOS', 'Android', 'Shopify', 'WooCommerce', 'Node.js', 'React / Next.js'],
    supportedIntegrationTypes: ['REST API', 'Hosted Checkout', 'Drop-in UI / Elements', 'Payment Links / No-Code'],
    supportedBusinessModels: ['SaaS', 'E-Commerce', 'Marketplace', 'Digital Downloads', 'Enterprise'],
    merchantEligibleCountryCodes: s.merchantCountries,
    merchantEligibilitySummary: s.merchantNote,
    customerPaymentCountryCodes: s.customerCountries || ALL_COUNTRIES,
    customerCoverageSummary: s.customerNote || `Accepts customer payments across 180+ countries in ${s.currencies.length}+ currencies.`,
    supportedCurrencies: s.currencies,
    settlementCurrencies: s.settlementCurrencies,
    transactionFees: s.fees,
    monthlyFees: s.monthlyFees || '$0 standard',
    setupFees: '$0',
    minimumTransactionAmount: '$0.50 USD equivalent',
    refundSupport: 'Full & Partial Refunds',
    refundDetails: `Supports API and dashboard full or partial refunds subject to ${s.brandName} settlement rules.`,
    recurringPaymentSupport: s.recurring,
    subscriptionSupport: s.subscriptions,
    recurringAndSubscriptionDetails: s.subscriptions
      ? `Supports automated subscription plans, webhooks, and recurring token billing.`
      : `Supports one-time checkout and vaulted recurring charges via API.`,
    chargebackSupport: s.cat !== 'crypto-gateways',
    chargebackDetails:
      s.cat === 'crypto-gateways'
        ? 'Blockchain transactions are irreversible on-chain; zero card chargebacks.'
        : 'Provides dispute notification webhooks and evidence upload workflows.',
    paymentLinksSupport: true,
    invoicingSupport: true,
    payoutSupport: true,
    payoutDetails: `Settles to verified merchant accounts in ${s.settlementCurrencies.join(', ')}.`,
    kycKybRequirements: s.kyc,
    businessEligibilityDetails: `Requires registered business or verified proprietor in supported jurisdictions (${s.merchantCountries.slice(0, 8).join(', ')}).`,
    onlinePaymentSupported: true,
    inPersonPaymentSupported: Boolean(s.inPerson),
    oneTimePaymentSupported: true,
    freeIntegrationAvailable: true,
    integrationComplexity: s.complexity || 'Low',
    features: s.features,
    advantages: s.pros,
    limitations: s.cons,
    alternativeIds: s.alts,
    linkedEntityIds: s.methods,
    cryptoDetails: s.crypto,
    popularityRank: s.rank,
  };
  return buildPaymentEntry(seed) as PaymentProvider;
}

